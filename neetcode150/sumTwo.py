import pytest 

def twoSum(nums: list[int], target: int) -> list[int]:
     pair:list[int] = []
     nums.sort()
     i = 0
     j = len(nums)-1
     while i<j:
          if(nums[i] + nums[j] > target):
               j-=1
               continue
          elif(nums[i] + nums[j] < target):
               i+=1
               continue
          elif(nums[i] + nums[j] == target):
               pair.append(nums[i])
               pair.append(nums[j])
               break
     return pair
            
